-- Migration 21: the durable authority-event journal and its delivery
-- cursor (issue #425, PR 3).
--
-- Migrations 16 and 18 made every committed Connection delete, service-token
-- rotate and revoke, and effective JWT revoke write one append-only evidence
-- row in the change's own transaction. Nothing delivered those rows anywhere:
-- a downstream audit system or SIEM could only poll three tables. This
-- migration adds the delivery side, without moving any network I/O into an
-- authority transaction.
--
-- - authority_event_journal is the commit-ordered index of evidence to
--   deliver. A producer appends one row in the SAME transaction as its
--   evidence row, carrying the evidence row's event_id and naming its
--   table, so the journal holds identifiers only: no actor, no resource
--   identifier, no secret material. The evidence rows stay the record; the
--   journal is the delivery obligation over them. event_id is the idempotency
--   key a consumer deduplicates on, minted once by the producer and never
--   regenerated by a retry or a redelivery.
-- - Positions come from authority_event_state.last_position, a counter row
--   the producer updates in its transaction, NOT from a sequence: the row
--   lock is held until COMMIT, so the next producer cannot take a position
--   until this one has committed or rolled back. Position order is commit
--   order, an aborted append's position is reused, and the committed journal
--   is gapless, which is what lets a cursor read "everything after N"
--   without ever skipping a late commit (ha-state-model.md section 2, rule
--   6; the audit stream of migrations 2 and 3 uses the same shape).
-- - The same update is the capacity reservation: it only succeeds while
--   retained_events < capacity, so a producer that finds the journal full
--   reserves nothing and its whole mutation rolls back. Accepted events are
--   never evicted to admit new ones. capacity is set at startup from
--   AUTHORITY_EVENT_JOURNAL_CAPACITY, which every replica must agree on (it
--   is part of the static-configuration fingerprint).
-- - authority_event_cursors holds the dispatcher's durable consumer cursor:
--   the last position a downstream sink accepted, under the execution-lease
--   fence of the replica that delivered it. A claim raises the fence and
--   never lowers it, and an advance is a compare-and-set on (fence,
--   position), so a fenced-out leader's late advance commits nothing. The
--   consumer vocabulary is closed; this slice has one consumer.
-- - Retention (the maintenance singleton) deletes journal rows only at or
--   below every cursor's position AND older than
--   AUTHORITY_EVENT_RETENTION_HOURS, and decrements retained_events in the
--   same statement. Before a dispatcher has ever claimed the cursor there is
--   no required consumer, and rows older than the retention window are
--   pruned by age alone. Retention never touches the evidence tables, which
--   stay append-only.
-- - authority_id is the persisted identity of this evidence authority, the
--   UUID every keyed safe reference is derived under. The first replica
--   that starts a dispatcher writes it once and nothing changes it
--   afterwards, so it survives restart and restore with the database.
--
-- Migration 19's admin_session_evidence is not journaled: a session
-- withdrawal must stay possible when the journal is full, which needs its
-- own capacity decision first.
--
-- Evidence committed before this migration is journaled here in commit
-- order (shared security revision, then commit time, then event ID), so the
-- first dispatcher delivers it like any other committed event. Its
-- journaled_at is the evidence row's own committed_at, so retention judges
-- it by its real age.

CREATE TABLE greengateway.authority_event_state (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    authority_id uuid,
    last_position bigint NOT NULL CHECK (last_position >= 0),
    retained_events bigint NOT NULL CHECK (retained_events >= 0),
    capacity bigint NOT NULL CHECK (capacity >= 1)
);

CREATE TABLE greengateway.authority_event_journal (
    position bigint PRIMARY KEY CHECK (position >= 1),
    event_id uuid NOT NULL UNIQUE,
    source text NOT NULL CHECK (
        source IN (
            'connection_change_evidence',
            'service_token_change_evidence',
            'jwt_revocation_evidence'
        )
    ),
    journaled_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE greengateway.authority_event_cursors (
    consumer text PRIMARY KEY CHECK (consumer IN ('dispatcher')),
    position bigint NOT NULL CHECK (position >= 0),
    fence bigint NOT NULL CHECK (fence >= 0),
    holder uuid NOT NULL,
    delivered_events bigint NOT NULL DEFAULT 0 CHECK (delivered_events >= 0),
    claimed_at timestamptz NOT NULL DEFAULT now(),
    advanced_at timestamptz
);

INSERT INTO greengateway.authority_event_journal (position, event_id, source, journaled_at)
SELECT row_number() OVER (ORDER BY existing.security_revision, existing.committed_at, existing.event_id),
       existing.event_id, existing.source, existing.committed_at
FROM (
    SELECT event_id, 'connection_change_evidence' AS source, security_revision, committed_at
    FROM greengateway.connection_change_evidence
    UNION ALL
    SELECT event_id, 'service_token_change_evidence', security_revision, committed_at
    FROM greengateway.service_token_change_evidence
    UNION ALL
    SELECT event_id, 'jwt_revocation_evidence', security_revision, committed_at
    FROM greengateway.jwt_revocation_evidence
) AS existing;

-- The capacity floor keeps an upgraded deployment with more history than
-- the default writable until startup applies the configured value.
INSERT INTO greengateway.authority_event_state (
    singleton, authority_id, last_position, retained_events, capacity
)
SELECT true, NULL, count(*), count(*), greatest(1000000, count(*))
FROM greengateway.authority_event_journal;
