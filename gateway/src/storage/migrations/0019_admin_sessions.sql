-- Migration 19: shared admin sessions for ADMIN_SESSION_MODE=cluster_postgres
-- (issue #424, ADR-0008).
--
-- The gateway issues its own admin session after a browser-bound OIDC
-- login. Standalone mode keeps those sessions in process memory; cluster
-- mode keeps them here so that every replica sees the same sessions and
-- the same withdrawals. Three tables:
--
-- - admin_session_logins: the pending cookie logins, so a logout on any
--   replica can cancel a completion still waiting on the IdP, or a session
--   issued for that login whose response never reached the browser
--   (issued_session_hash). binding_hash is a digest of the login's browser
--   binding, never the binding.
-- - admin_sessions: one row per live session. session_hash is a digest of
--   the 256-bit cookie value, csrf_hash a digest of the double-submit token
--   the session is bound to; neither value is stored. Digests are SHA-256
--   over a purpose label and the deployment ID, computed by the gateway.
--   The provider access token the gateway revalidates on every request is
--   sealed with XChaCha20-Poly1305 under ADMIN_LOGIN_KEYRING (key_id names
--   the key), with the deployment ID, session_hash and id bound as
--   associated data. user_id and issuer are the identity the session was
--   issued to, bounded like every principal (auth/principal.rs). Deadlines
--   are the database clock's: expires_at is fixed at issuance, and
--   idle_expires_at moves on each admitted request and never past
--   expires_at, so a session is live exactly while idle_expires_at is in
--   the future.
-- - admin_session_evidence: one append-only row per grant and per
--   withdrawal, written in the same statement or transaction as the change.
--   reason says which withdrawal it was: logout (the session cookie or the
--   login binding was presented to logout), replaced (a new sign-in in the
--   same browser), rejected (the provider no longer accepts the access
--   token, or it names another identity) or expired (removed by the bounded
--   prune after its idle or absolute deadline; committed_at is then the
--   prune's time, not the deadline's). A session has at most one row per
--   action. No foreign key: the session row is deleted by every withdrawal,
--   and the evidence must outlive it. Identifiers, the identity and the
--   absolute deadline only; nothing here is a credential. event_id is
--   generated by the database (gen_random_uuid, core since PostgreSQL 13).
--   Rows are never updated or deleted by the gateway; their delivery and
--   retention belong to later #425 slices.
--
-- Nothing is backfilled: no session exists before this migration, because
-- cluster mode refused ADMIN_SESSION_MODE until it.

CREATE TABLE greengateway.admin_session_logins (
    binding_hash text PRIMARY KEY CHECK (
        octet_length(binding_hash) = 64 AND binding_hash ~ '^[0-9a-f]+$'
    ),
    issued_session_hash text CHECK (
        issued_session_hash IS NULL
        OR (octet_length(issued_session_hash) = 64 AND issued_session_hash ~ '^[0-9a-f]+$')
    ),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX idx_ggw_admin_session_logins_expires
    ON greengateway.admin_session_logins(expires_at);

CREATE INDEX idx_ggw_admin_session_logins_issued
    ON greengateway.admin_session_logins(issued_session_hash);

CREATE TABLE greengateway.admin_sessions (
    session_hash text PRIMARY KEY CHECK (
        octet_length(session_hash) = 64 AND session_hash ~ '^[0-9a-f]+$'
    ),
    id uuid NOT NULL UNIQUE,
    csrf_hash text NOT NULL CHECK (
        octet_length(csrf_hash) = 64 AND csrf_hash ~ '^[0-9a-f]+$'
    ),
    user_id text NOT NULL CHECK (octet_length(user_id) BETWEEN 1 AND 4096),
    issuer text CHECK (issuer IS NULL OR octet_length(issuer) <= 4096),
    key_id text NOT NULL CHECK (octet_length(key_id) BETWEEN 1 AND 128),
    token_nonce bytea NOT NULL CHECK (octet_length(token_nonce) = 24),
    token_ct bytea NOT NULL CHECK (octet_length(token_ct) BETWEEN 17 AND 32784),
    created_at timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    idle_expires_at timestamptz NOT NULL,
    CHECK (expires_at > created_at),
    CHECK (idle_expires_at <= expires_at)
);

CREATE INDEX idx_ggw_admin_sessions_idle_expires
    ON greengateway.admin_sessions(idle_expires_at);

CREATE TABLE greengateway.admin_session_evidence (
    event_id uuid PRIMARY KEY,
    operation_id uuid NOT NULL,
    session_id uuid NOT NULL,
    action text NOT NULL CHECK (
        action IN ('admin_session.grant', 'admin_session.withdraw')
    ),
    reason text NOT NULL CHECK (
        (action = 'admin_session.grant' AND reason = 'issued')
        OR (action = 'admin_session.withdraw'
            AND reason IN ('logout', 'replaced', 'rejected', 'expired'))
    ),
    user_id text NOT NULL CHECK (octet_length(user_id) BETWEEN 1 AND 4096),
    issuer text CHECK (issuer IS NULL OR octet_length(issuer) <= 4096),
    expires_at timestamptz NOT NULL,
    committed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (session_id, action)
);
