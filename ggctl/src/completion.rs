//! Shell completion scripts, generated from the command table.
//!
//! Every script completes the command names, each command's options, the
//! fixed choices of choice-valued options and arguments, and file names for
//! path-valued options. All text in a script comes from the static command
//! table and is quoted for the target shell.

use std::fmt::Write as _;

use crate::{
    cli::{CommandSpec, Invocation, OptionSpec, ValueKind, COMMANDS},
    diagnostic::Exit,
    report::{self, Io},
};

/// `ggctl completion SHELL`.
pub(crate) fn run(invocation: &Invocation, io: &mut Io<'_>) -> Exit {
    let script = match invocation.positional(0).map(|(_, shell)| shell) {
        Some("bash") => bash(),
        Some("zsh") => zsh(),
        Some("fish") => fish(),
        _ => powershell(),
    };
    report::artifact(io, &script)
}

fn option_names(command: &CommandSpec) -> Vec<&'static str> {
    command
        .options
        .iter()
        .map(|option| option.name)
        .chain(["--help", "-h"])
        .collect()
}

fn positional_choices(command: &CommandSpec) -> &'static [&'static str] {
    match command.arguments.first().map(|argument| argument.kind) {
        Some(ValueKind::Choice(choices)) => choices,
        _ => &[],
    }
}

/// Whether the command's positional argument is a path, which completes
/// directory names: every such argument today is a bundle directory.
fn takes_a_directory(command: &CommandSpec) -> bool {
    command
        .arguments
        .first()
        .is_some_and(|argument| argument.kind == ValueKind::Path)
}

/// Single-quotes text for a POSIX shell, zsh or fish.
fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

fn bash() -> String {
    let mut script = String::from(
        "# bash completion for ggctl, generated by `ggctl completion bash` from the same\n\
         # command table as `ggctl help`.\n\
         _ggctl() {\n    \
             local cur prev\n    \
             cur=\"${COMP_WORDS[COMP_CWORD]}\"\n    \
             prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n    \
             if [ \"$COMP_CWORD\" -eq 1 ]; then\n",
    );
    let commands: Vec<_> = COMMANDS.iter().map(|command| command.name).collect();
    let _ = writeln!(
        script,
        "        COMPREPLY=($(compgen -W {} -- \"$cur\"))\n        return 0\n    fi\n    case \"${{COMP_WORDS[1]}}\" in",
        single_quoted(&commands.join(" "))
    );
    for command in COMMANDS {
        let _ = writeln!(script, "        {})", command.name);
        let _ = writeln!(script, "            case \"$prev\" in");
        for option in command.options {
            match option.value.map(|(_, kind)| kind) {
                Some(ValueKind::Path) => {
                    let _ = writeln!(
                        script,
                        "                {}) COMPREPLY=($(compgen -f -- \"$cur\")); return 0 ;;",
                        option.name
                    );
                }
                Some(ValueKind::Choice(choices)) => {
                    let _ = writeln!(
                        script,
                        "                {}) COMPREPLY=($(compgen -W {} -- \"$cur\")); return 0 ;;",
                        option.name,
                        single_quoted(&choices.join(" "))
                    );
                }
                Some(_) => {
                    let _ = writeln!(
                        script,
                        "                {}) COMPREPLY=(); return 0 ;;",
                        option.name
                    );
                }
                None => {}
            }
        }
        let words: Vec<_> = positional_choices(command)
            .iter()
            .copied()
            .chain(option_names(command))
            .collect();
        let directories = if takes_a_directory(command) {
            "$(compgen -d -- \"$cur\") "
        } else {
            ""
        };
        let _ = writeln!(
            script,
            "            esac\n            COMPREPLY=({directories}$(compgen -W {} -- \"$cur\"))\n            ;;",
            single_quoted(&words.join(" "))
        );
    }
    script.push_str("    esac\n    return 0\n}\ncomplete -F _ggctl ggctl\n");
    script
}

/// Escapes text inside a zsh `_arguments` or `_describe` spec.
fn zsh_spec(text: &str) -> String {
    text.chars()
        .flat_map(|character| match character {
            '[' | ']' | ':' | '\\' => vec!['\\', character],
            other => vec![other],
        })
        .collect()
}

fn zsh_option(option: &OptionSpec) -> String {
    let description = zsh_spec(option.help);
    let spec = match option.value {
        None => format!("{}[{description}]", option.name),
        Some((placeholder, ValueKind::Path)) => {
            format!("{}[{description}]:{placeholder}:_files", option.name)
        }
        Some((placeholder, ValueKind::Choice(choices))) => {
            format!(
                "{}[{description}]:{placeholder}:({})",
                option.name,
                choices.join(" ")
            )
        }
        Some((placeholder, _)) => format!("{}[{description}]:{placeholder}: ", option.name),
    };
    single_quoted(&spec)
}

fn zsh() -> String {
    let mut script = String::from(
        "#compdef ggctl\n\
         # zsh completion for ggctl, generated by `ggctl completion zsh` from the same\n\
         # command table as `ggctl help`.\n\
         _ggctl() {\n  \
           local -a commands\n  \
           commands=(\n",
    );
    for command in COMMANDS {
        let _ = writeln!(
            script,
            "    {}",
            single_quoted(&format!("{}:{}", command.name, zsh_spec(command.summary)))
        );
    }
    script.push_str(
        "  )\n  \
           if (( CURRENT == 2 )); then\n    \
             _describe -t commands 'ggctl command' commands\n    \
             return\n  \
           fi\n  \
           local command=\"${words[2]}\"\n  \
           shift words\n  \
           (( CURRENT-- ))\n  \
           case \"$command\" in\n",
    );
    for command in COMMANDS {
        let _ = writeln!(script, "    {})\n      _arguments \\", command.name);
        for option in command.options {
            let _ = writeln!(script, "        {} \\", zsh_option(option));
        }
        if let Some(argument) = command.arguments.first() {
            let action = if takes_a_directory(command) {
                "_files -/".to_owned()
            } else {
                format!("({})", positional_choices(command).join(" "))
            };
            let _ = writeln!(
                script,
                "        {} \\",
                single_quoted(&format!("1:{}:{action}", argument.name))
            );
        }
        let _ = writeln!(
            script,
            "        '(- *)'{{-h,--help}}'[print this help]'\n      ;;"
        );
    }
    // Autoloaded from `fpath`, the file is the body of `_ggctl` and must
    // complete; sourced, it registers the function instead.
    script.push_str(
        "  esac\n}\n\
         if [ \"$funcstack[1]\" = \"_ggctl\" ]; then\n  \
           _ggctl \"$@\"\n\
         else\n  \
           compdef _ggctl ggctl\n\
         fi\n",
    );
    script
}

fn fish() -> String {
    let mut script = String::from(
        "# fish completion for ggctl, generated by `ggctl completion fish` from the same\n\
         # command table as `ggctl help`.\n\
         complete -c ggctl -f\n",
    );
    let names: Vec<_> = COMMANDS.iter().map(|command| command.name).collect();
    for command in COMMANDS {
        let _ = writeln!(
            script,
            "complete -c ggctl -n {} -a {} -d {}",
            single_quoted(&format!(
                "not __fish_seen_subcommand_from {}",
                names.join(" ")
            )),
            command.name,
            single_quoted(command.summary)
        );
    }
    for command in COMMANDS {
        let condition = single_quoted(&format!("__fish_seen_subcommand_from {}", command.name));
        for option in command.options {
            let long = &option.name[2..];
            let line = match option.value.map(|(_, kind)| kind) {
                None => format!("complete -c ggctl -n {condition} -l {long}"),
                Some(ValueKind::Path) => {
                    format!("complete -c ggctl -n {condition} -l {long} -r -F")
                }
                Some(ValueKind::Choice(choices)) => format!(
                    "complete -c ggctl -n {condition} -l {long} -x -a {}",
                    single_quoted(&choices.join(" "))
                ),
                Some(_) => format!("complete -c ggctl -n {condition} -l {long} -x"),
            };
            let _ = writeln!(script, "{line} -d {}", single_quoted(option.help));
        }
        let choices = positional_choices(command);
        if !choices.is_empty() {
            let _ = writeln!(
                script,
                "complete -c ggctl -n {condition} -a {}",
                single_quoted(&choices.join(" "))
            );
        }
        if takes_a_directory(command) {
            let _ = writeln!(
                script,
                "complete -c ggctl -n {condition} -a '(__fish_complete_directories)'"
            );
        }
        let _ = writeln!(
            script,
            "complete -c ggctl -n {condition} -s h -l help -d 'print this help'"
        );
    }
    script
}

/// Single-quotes text for PowerShell.
fn powershell_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn powershell_list(words: &[&str]) -> String {
    let quoted: Vec<_> = words.iter().map(|word| powershell_quoted(word)).collect();
    format!("@({})", quoted.join(", "))
}

fn powershell() -> String {
    let mut script = String::from(
        "# PowerShell completion for ggctl, generated by `ggctl completion powershell`\n\
         # from the same command table as `ggctl help`. Add it to your profile.\n\
         Register-ArgumentCompleter -Native -CommandName ggctl -ScriptBlock {\n    \
             param($wordToComplete, $commandAst, $cursorPosition)\n    \
             $words = @{\n",
    );
    for command in COMMANDS {
        let words: Vec<_> = positional_choices(command)
            .iter()
            .copied()
            .chain(option_names(command))
            .collect();
        let _ = writeln!(
            script,
            "        {} = {}",
            powershell_quoted(command.name),
            powershell_list(&words)
        );
    }
    script.push_str("    }\n    $values = @{\n");
    for command in COMMANDS {
        let _ = writeln!(script, "        {} = @{{", powershell_quoted(command.name));
        for option in command.options {
            match option.value.map(|(_, kind)| kind) {
                Some(ValueKind::Choice(choices)) => {
                    let _ = writeln!(
                        script,
                        "            {} = {}",
                        powershell_quoted(option.name),
                        powershell_list(choices)
                    );
                }
                // A path option completes file names: returning nothing
                // leaves PowerShell's own path completion in place.
                Some(ValueKind::Path) => {}
                Some(_) => {
                    let _ = writeln!(
                        script,
                        "            {} = @()",
                        powershell_quoted(option.name)
                    );
                }
                None => {}
            }
        }
        script.push_str("        }\n");
    }
    let commands: Vec<_> = COMMANDS.iter().map(|command| command.name).collect();
    let mut path_options: Vec<_> = COMMANDS
        .iter()
        .flat_map(|command| command.options)
        .filter(|option| matches!(option.value, Some((_, ValueKind::Path))))
        .map(|option| option.name)
        .collect();
    path_options.sort_unstable();
    path_options.dedup();
    let directory_commands: Vec<_> = COMMANDS
        .iter()
        .filter(|command| takes_a_directory(command))
        .map(|command| command.name)
        .collect();
    let _ = write!(
        script,
        "    }}\n    \
             $elements = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object {{ $_.ToString() }})\n    \
             if ($wordToComplete -ne '') {{ $elements = @($elements | Select-Object -SkipLast 1) }}\n    \
             if ($elements.Count -eq 0) {{\n        \
                 $candidates = {}\n    \
             }} elseif ($words.ContainsKey($elements[0])) {{\n        \
                 $command = $elements[0]\n        \
                 $previous = $elements[-1]\n        \
                 if ($elements.Count -gt 1 -and $values[$command].ContainsKey($previous)) {{\n            \
                     $candidates = $values[$command][$previous]\n        \
                 }} elseif ($previous -in {}) {{\n            \
                     return\n        \
                 }} elseif ($wordToComplete -notlike '-*' -and $command -in {}) {{\n            \
                     return\n        \
                 }} else {{\n            \
                     $candidates = $words[$command]\n        \
                 }}\n    \
             }} else {{\n        \
                 return\n    \
             }}\n    \
             $candidates | Where-Object {{ $_ -like \"$wordToComplete*\" }} | ForEach-Object {{\n        \
                 [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)\n    \
             }}\n\
         }}\n",
        powershell_list(&commands),
        powershell_list(&path_options),
        powershell_list(&directory_commands)
    );
    script
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scripts() -> [(&'static str, String); 4] {
        [
            ("bash", bash()),
            ("zsh", zsh()),
            ("fish", fish()),
            ("powershell", powershell()),
        ]
    }

    #[test]
    fn every_script_completes_every_command_option_and_choice() {
        for (shell, script) in scripts() {
            for command in COMMANDS {
                assert!(script.contains(command.name), "{shell}: {}", command.name);
                for option in command.options {
                    let name = if shell == "fish" {
                        &option.name[2..]
                    } else {
                        option.name
                    };
                    assert!(script.contains(name), "{shell}: {}", option.name);
                    if let Some((_, ValueKind::Choice(choices))) = option.value {
                        for choice in choices {
                            assert!(script.contains(choice), "{shell}: {choice}");
                        }
                    }
                }
                for choice in positional_choices(command) {
                    assert!(script.contains(choice), "{shell}: {choice}");
                }
            }
        }
    }

    #[test]
    fn quoting_survives_hostile_text() {
        assert_eq!(single_quoted("it's"), r"'it'\''s'");
        assert_eq!(powershell_quoted("it's"), "'it''s'");
        assert_eq!(zsh_spec("a[b]:c\\"), r"a\[b\]\:c\\");
    }

    #[test]
    fn scripts_are_balanced_and_register_ggctl() {
        let [bash, zsh, fish, powershell] = scripts().map(|(_, script)| script);
        assert!(bash.ends_with("complete -F _ggctl ggctl\n"));
        assert!(zsh.starts_with("#compdef ggctl\n") && zsh.contains("\n  compdef _ggctl ggctl\n"));
        assert!(fish
            .lines()
            .skip(2)
            .all(|line| line.starts_with("complete -c ggctl ")));
        assert!(powershell.contains("Register-ArgumentCompleter -Native -CommandName ggctl"));
        for script in [&bash, &zsh, &powershell] {
            assert_eq!(script.matches('{').count(), script.matches('}').count());
        }
        // `case` arms close a parenthesis they never open, so only
        // PowerShell is expected to pair every one.
        assert_eq!(
            powershell.matches('(').count(),
            powershell.matches(')').count()
        );
        assert!(powershell.contains("$previous -in @('--against', '--ca-file', '--token-file')"));
        // A bundle directory completes directory names.
        assert!(bash
            .contains("            COMPREPLY=($(compgen -d -- \"$cur\") $(compgen -W '--strict"));
        assert!(zsh.contains("'1:BUNDLE:_files -/'"));
        assert!(fish.contains(
            "complete -c ggctl -n '__fish_seen_subcommand_from doctor' -a '(__fish_complete_directories)'\n"
        ));
        assert!(powershell.contains("$command -in @('validate', 'doctor', 'diff')"));
        for script in [&bash, &zsh, &fish] {
            // Single quotes pair up once escaped quotes are removed.
            assert_eq!(script.replace(r"'\''", "").matches('\'').count() % 2, 0);
        }
        assert_eq!(powershell.replace("''", "").matches('\'').count() % 2, 0);
    }
}
