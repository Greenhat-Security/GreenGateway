class VerifyTests(Workspace):
    def verifier(self, mode="clean"):
        calls = []

        def run(command, **kwargs):
            calls.append(command)
            if command[1:] == ["--version"]:
                return "gh version " + release.versions()["github_cli"] + " (fixture)\n"
            if mode == "rejected":
                raise subprocess.CalledProcessError(1, command)
            path = Path(command[3])
            predicate = command[command.index("--predicate-type") + 1]
            digest = hashlib.sha256(path.read_bytes()).hexdigest() if mode != "other-digest" else "f" * 64
            statements = [] if mode == "empty" else [{"predicateType": predicate,
                                                      "subject": [{"name": path.name, "digest": {"sha256": digest}}]}]
            return json.dumps([{"verificationResult": {"statement": s}} for s in statements])
        return calls, run

    def test_every_entry_is_verified_against_the_release_identity(self):
        self.assemble(TAG)
        self.sign()
        calls, run = self.verifier()
        with patch.object(release, "run_utf8", side_effect=run):
            self.assertEqual(release.verify(self.dist, "gh", root=self.root), 1 + 3 * len(release.TARGETS))
        self.assertEqual(len(calls), 2 + 3 * len(release.TARGETS))
        for call in calls[1:]:
            for flag, expected in [("--repo", REPO), ("--signer-workflow", REPO + "/" + release.WORKFLOW),
                                   ("--signer-digest", SHA), ("--source-digest", SHA), ("--source-ref", TAG),
                                   ("--cert-oidc-issuer", "https://token.actions.githubusercontent.com")]:
                self.assertEqual(call[call.index(flag) + 1], expected)
            self.assertIn("--deny-self-hosted-runners", call)
            self.assertTrue(Path(call[call.index("--bundle") + 1]).is_file())
        verified = {(Path(call[3]).name, call[call.index("--predicate-type") + 1]) for call in calls[1:]}
        for target in release.TARGETS:
            self.assertIn((release.archive_name(VERSION, target), release.SPDX), verified)
            self.assertIn((release.sbom_name(VERSION, target), release.PROVENANCE), verified)
        self.assertIn((release.CHECKSUMS, release.PROVENANCE), verified)

    def test_a_rejected_unconfirmed_or_unchecked_release_fails(self):
        self.assemble(TAG)
        self.sign()
        for mode, error in [("rejected", subprocess.CalledProcessError), ("empty", ValueError),
                            ("other-digest", ValueError)]:
            _, run = self.verifier(mode)
            with self.subTest(mode=mode), patch.object(release, "run_utf8", side_effect=run), \
                    self.assertRaises(error):
                release.verify(self.dist, "gh", root=self.root)
        (self.dist / release.sbom_bundle_name(VERSION, "x86_64-apple-darwin")).unlink()
        calls, run = self.verifier()
        with patch.object(release, "run_utf8", side_effect=run), self.assertRaises(ValueError):
            release.verify(self.dist, "gh", root=self.root)
        self.assertEqual(calls, [], "nothing is verified before the release check passes")

    def test_verifier_version_drift_fails_before_verifying(self):
        self.assemble(TAG)
        self.sign()
        with patch.object(release, "run_utf8", return_value="gh version 0.0.1 (fixture)\n") as run, \
                self.assertRaises(ValueError):
            release.verify(self.dist, "gh", root=self.root)
        self.assertEqual(run.call_count, 1)


