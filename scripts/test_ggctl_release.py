LOCK_TOML = "".join(
    f'[[package]]\nname = "{p["name"]}"\nversion = "{p["version"]}"\n'
    + (f'source = "{p["source"]}"\nchecksum = "{p["checksum"]}"\n' if "source" in p else "") + "\n"
    for p in LOCK["package"])


def sbom(**changes):
    arguments = {"target": "x86_64-unknown-linux-gnu", "version": VERSION, "archive": "a.tar.gz",
                 "archive_sha256": "4" * 64, "binary_sha256": "5" * 64, "epoch": int(EPOCH),
                 "repository": REPO, "sha": SHA, "license_id": "Apache-2.0", **changes}
    return release.sbom_document(metadata(), LOCK, **arguments)


def statement_bundle(statements):
    lines = []
    for statement in statements:
        payload = base64.b64encode(json.dumps(statement).encode()).decode()
        lines.append(json.dumps({"mediaType": "application/vnd.dev.sigstore.bundle.v0.3+json",
                                 "dsseEnvelope": {"payloadType": "application/vnd.in-toto+json",
                                                  "payload": payload, "signatures": [{"sig": "fixture"}]}}))
    return ("\n".join(lines) + "\n").encode()


def subject(path):
    return {"name": path.name, "digest": {"sha256": hashlib.sha256(path.read_bytes()).hexdigest()}}


class Workspace(unittest.TestCase):
    """A temporary repository root with ggctl's manifest and LICENSE and a
    fixture lockfile, and a release directory packaged from fake builds."""

    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name) / "repo"
        (self.root / "ggctl").mkdir(parents=True)
        shutil.copyfile(ROOT / "ggctl/Cargo.toml", self.root / "ggctl/Cargo.toml")
        (self.root / "LICENSE").write_bytes((ROOT / "LICENSE").read_bytes())
        (self.root / "Cargo.lock").write_text(LOCK_TOML, encoding="utf-8")
        self.binary = Path(temporary.name) / "ggctl"
        self.binary.write_bytes(b"\x7fELF fixture executable")
        self.dist = Path(temporary.name) / "dist"
        environment = patch.dict(os.environ, {"SOURCE_DATE_EPOCH": EPOCH})
        environment.start()
        self.addCleanup(environment.stop)

    def package(self, target, output=None, run=None):
        return release.package(self.binary, target, output or self.dist, REPO, SHA, root=self.root,
                               run=run or fake_ggctl(), metadata=metadata())

    def assemble(self, ref="refs/pull/7/merge"):
        for target in release.TARGETS:
            self.package(target)
        release.write_checksums(self.dist, VERSION)
        self.write_manifest(ref)

    def write_manifest(self, ref):
        manifest = release.release_manifest(self.dist, VERSION, REPO, SHA, ref)
        release.write_bytes(self.dist / release.manifest_name(VERSION), release.json_bytes(manifest))
        return manifest

    def edit_manifest(self, change):
        path = self.dist / release.manifest_name(VERSION)
        manifest = json.loads(path.read_bytes())
        change(manifest)
        path.write_bytes(release.json_bytes(manifest))

    def check(self, dry_run=True):
        return release.check(self.dist, dry_run, root=self.root)

    def refused(self, fragment, dry_run=True):
        with self.assertRaises((ValueError, OSError, KeyError)) as raised:
            self.check(dry_run)
        self.assertIn(fragment, str(raised.exception))

    def sign(self):
        """Writes the bundles the release job would: one provenance statement
        over every archive, SBOM and SHA256SUMS, and one SBOM statement per
        archive whose predicate is that archive's SBOM."""
        names = sorted(path for path in self.dist.iterdir() if path.name.endswith((".tar.gz", ".zip", ".spdx.json"))
                       or path.name == release.CHECKSUMS)
        provenance = {"_type": "https://in-toto.io/Statement/v1", "predicateType": release.PROVENANCE,
                      "subject": [subject(path) for path in names], "predicate": {}}
        (self.dist / release.provenance_bundle_name(VERSION)).write_bytes(statement_bundle([provenance]))
        for target in release.TARGETS:
            archive = self.dist / release.archive_name(VERSION, target)
            document = json.loads((self.dist / release.sbom_name(VERSION, target)).read_bytes())
            statement = {"_type": "https://in-toto.io/Statement/v1", "predicateType": release.SPDX,
                         "subject": [subject(archive)], "predicate": document}
            (self.dist / release.sbom_bundle_name(VERSION, target)).write_bytes(statement_bundle([statement]))


class VersionTests(unittest.TestCase):
    def test_a_tag_must_name_the_cargo_version_exactly(self):
        self.assertTrue(release.VERSION.fullmatch(VERSION))
        self.assertEqual(release.release_version(TAG), VERSION)
        self.assertEqual(release.release_version("refs/pull/7/merge"), VERSION)
        self.assertEqual(release.release_version(""), VERSION)
        for ref in ["refs/tags/v" + VERSION, "refs/tags/ggctl-v9.9.9", TAG + "-rc.1", "refs/tags/ggctl-" + VERSION]:
            with self.subTest(ref=ref), self.assertRaises(ValueError):
                release.release_version(ref)

    def test_the_cargo_version_must_be_exact(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "ggctl").mkdir()
            for version in ['"0.1"', '"0.1.0-alpha.1"', '"01.0.0"', "1"]:
                (root / "ggctl/Cargo.toml").write_text(f'[package]\nname = "ggctl"\nversion = {version}\n')
                with self.subTest(version=version), self.assertRaises(ValueError):
                    release.cargo_version(root)

    def test_names_follow_the_target_and_refuse_any_other(self):
        self.assertEqual(release.archive_name("1.2.3", "x86_64-pc-windows-msvc"), "ggctl-1.2.3-x86_64-pc-windows-msvc.zip")
        self.assertEqual(release.archive_name("1.2.3", "aarch64-apple-darwin"), "ggctl-1.2.3-aarch64-apple-darwin.tar.gz")
        self.assertEqual(release.executable_name("x86_64-pc-windows-msvc"), "ggctl.exe")
        with self.assertRaises(ValueError):
            release.archive_name("1.2.3", "x86_64-unknown-linux-musl")


class ManPageTests(unittest.TestCase):
    def test_parity_holds_each_page_to_its_help(self):
        for help_text, page in [(OVERVIEW, MAN_OVERVIEW), (HELP_VERSION, MAN_VERSION), (HELP_HELP, MAN_HELP),
                                (HELP_LEDGER, MAN_LEDGER), (HELP_LEDGER_SEED, MAN_LEDGER_SEED)]:
            release.require_parity(help_text, page, "fixture")
        dropped = MAN_VERSION.replace("human (default) or json", "human (default)")
        for page, fragment in [(dropped, "human (default) or json"),
                               (MAN_VERSION.replace(r"\fB\-\-format\fR \fIFORMAT\fR", r"\fB\-\-form\fR"), "--format FORMAT"),
                               (MAN_HELP.replace("\\fICOMMAND\\fR\n", ""), "COMMAND the command"),
                               (MAN_VERSION.replace("[OPTIONS]", ""), "ggctl version [OPTIONS]")]:
            with self.subTest(fragment=fragment), self.assertRaises(ValueError) as raised:
                release.require_parity(HELP_VERSION if "version" in page.splitlines()[1].lower() else HELP_HELP,
                                       page, "fixture")
            self.assertIn(fragment[:12], str(raised.exception))
        with self.assertRaises(ValueError):
            release.require_parity(HELP_VERSION, MAN_VERSION.split("\n", 1)[1], "fixture")
        with self.assertRaises(ValueError) as raised:
            release.require_parity(HELP_LEDGER, MAN_LEDGER.replace(".br\n\\fBggctl help ledger\\fR [COMMAND]\n", ""),
                                   "fixture")
        self.assertIn("ggctl help ledger [COMMAND]", str(raised.exception))

    def test_help_blocks_are_paragraphs_entries_and_usage_lines(self):
        self.assertEqual(release.help_blocks(HELP_VERSION), [
            "ggctl version [OPTIONS]", "Prints the ggctl version.",
            "--format FORMAT human (default) or json: one GgctlReport document on standard output",
            "-h, --help print this help"])
        self.assertIn("ggctl help [COMMAND]", release.help_blocks(OVERVIEW))
        self.assertNotIn(f"ggctl {VERSION} - the GreenGateway operator CLI", release.help_blocks(OVERVIEW))
        self.assertEqual(release.rendered("\\fB\\-\\-x\\fR \\e\n\\&.y\n.TP\n"), "--x \\ .y")

    def test_the_overview_lists_the_commands(self):
        self.assertEqual(release.listed_commands(OVERVIEW), ["version", "ledger seed", "help"])
        for overview in ["Usage: ggctl\n", OVERVIEW.replace("  help ", "  version "),
                         OVERVIEW.replace("  help ", "  Help/../ ")]:
            with self.assertRaises(ValueError):
                release.listed_commands(overview)


class ArchiveTests(Workspace):
    def test_members_come_from_the_binary_and_its_help(self):
        files = release.members(self.binary, "x86_64-unknown-linux-gnu", VERSION, "Apache\r\nLicense\r\n", fake_ggctl())
        self.assertEqual([path for path, _, _ in files], [
            "LICENSE", "completion/_ggctl", "completion/ggctl.bash", "completion/ggctl.fish",
            "completion/ggctl.ps1", "ggctl", "man/man1/ggctl-help.1", "man/man1/ggctl-ledger-seed.1",
            "man/man1/ggctl-ledger.1", "man/man1/ggctl-version.1", "man/man1/ggctl.1"])
        modes = {path: mode for path, _, mode in files}
        self.assertEqual(modes["ggctl"], 0o755)
        self.assertEqual(modes["man/man1/ggctl.1"], 0o644)
        self.assertEqual(dict((path, data) for path, data, _ in files)["LICENSE"], b"Apache\nLicense\n")
        windows = release.members(self.binary, "x86_64-pc-windows-msvc", VERSION, "x", fake_ggctl())
        self.assertIn("ggctl.exe", [path for path, _, _ in windows])

    def test_a_wrong_version_a_drifted_page_or_a_failing_command_is_refused(self):
        for changes in [{("--version",): "ggctl 9.9.9\n"},
                        {("help", "--man", "version"): MAN_VERSION.replace("print this help", "print help")},
                        {("help", "--man", "help"): MAN_HELP.replace("\n", "\r\n")},
                        {("completion", "zsh"): "# zsh \u00e9\n"}]:
            with self.subTest(changes=changes), self.assertRaises(ValueError):
                release.members(self.binary, "x86_64-unknown-linux-gnu", VERSION, "x", fake_ggctl(changes))
        run = fake_ggctl()
        with self.assertRaises(ValueError):
            release.members(self.binary, "x86_64-unknown-linux-gnu", VERSION, "x",
                            lambda binary, *args: b"" if args == ("completion", "fish") else run(binary, *args))

    def test_archives_depend_only_on_their_input(self):
        files = [("ggctl", b"binary", 0o755), ("man/man1/ggctl.1", b"page\n", 0o644), ("LICENSE", b"text\n", 0o644)]
        first, second = release.tar_gz("top", files, 1767225600), release.tar_gz("top", list(reversed(files)), 1767225600)
        self.assertEqual(first, second)
        self.assertNotEqual(first, release.tar_gz("top", files, 1767225601))
        self.assertEqual(first[3] & 0x08, 0, "no file name in the gzip header")
        self.assertEqual(int.from_bytes(first[4:8], "little"), 1767225600)
        with tarfile.open(fileobj=io.BytesIO(first)) as archive:
            members = archive.getmembers()
        self.assertEqual([m.name for m in members], ["top", "top/LICENSE", "top/ggctl", "top/man", "top/man/man1",
                                                     "top/man/man1/ggctl.1"])
        for member in members:
            self.assertEqual((member.uid, member.gid, member.uname, member.gname, member.mtime), (0, 0, "", "", 1767225600))
        self.assertEqual({m.name: m.mode for m in members}["top/ggctl"], 0o755)
        self.assertTrue(members[3].isdir())

        packed = release.zip_archive("top", files, 1767225600)
        self.assertEqual(packed, release.zip_archive("top", list(reversed(files)), 1767225600))
        with zipfile.ZipFile(io.BytesIO(packed)) as archive:
            infos = archive.infolist()
            self.assertEqual(archive.read("top/ggctl"), b"binary")
        self.assertEqual([info.filename for info in infos], ["top/", "top/LICENSE", "top/ggctl", "top/man/",
                                                            "top/man/man1/", "top/man/man1/ggctl.1"])
        self.assertEqual(infos[2].external_attr >> 16, 0o100755)
        self.assertEqual(infos[2].date_time, (2026, 1, 1, 0, 0, 0))
        early = release.zip_archive("top", files, 0)
        with zipfile.ZipFile(io.BytesIO(early)) as archive:
            self.assertEqual(archive.infolist()[1].date_time, (1980, 1, 1, 0, 0, 0))

    def test_packaging_twice_reproduces_and_compare_says_so(self):
        target = "aarch64-unknown-linux-gnu"
        self.package(target, self.dist / "first")
        self.package(target, self.dist / "second")
        release.compare(self.dist / "first", self.dist / "second")
        with self.assertRaises(ValueError):
            self.package(target, self.dist / "first")
        sbom_path = self.dist / "second" / release.sbom_name(VERSION, target)
        sbom_path.write_bytes(sbom_path.read_bytes().replace(b'"SPDX-2.3"', b'"SPDX-2.3" '))
        with self.assertRaises(ValueError) as raised:
            release.compare(self.dist / "first", self.dist / "second")
        self.assertIn("not reproducible", str(raised.exception))
        (self.dist / "second" / "extra").write_bytes(b"")
        with self.assertRaises(ValueError):
            release.compare(self.dist / "first", self.dist / "second")

    def test_the_package_holds_the_man_pages_and_completions(self):
        archive = self.package("x86_64-apple-darwin")
        with tarfile.open(archive) as opened:
            top = f"ggctl-{VERSION}-x86_64-apple-darwin"
            self.assertEqual(opened.extractfile(top + "/man/man1/ggctl-version.1").read().decode(), MAN_VERSION)
            self.assertEqual(opened.extractfile(top + "/completion/_ggctl").read(), b"# zsh completion for ggctl\n")
            self.assertEqual(opened.extractfile(top + "/ggctl").read(), self.binary.read_bytes())
            self.assertNotIn(b"\r\n", opened.extractfile(top + "/LICENSE").read())


class SbomTests(unittest.TestCase):
    def test_the_inventory_is_the_target_build_graph_without_dev_dependencies(self):
        document = sbom()
        self.assertEqual(document, sbom(), "deterministic")
        packages = {package["SPDXID"]: package for package in document["packages"]}
        self.assertEqual({package["name"] for package in document["packages"]},
                         {"a.tar.gz", "ggctl", "gateway-config", "serde", "cc"})
        self.assertEqual(document["packages"][0]["SPDXID"], "SPDXRef-Archive")
        relations = {(r["spdxElementId"], r["relationshipType"], r["relatedSpdxElement"]) for r in document["relationships"]}
        self.assertEqual(relations, {
            ("SPDXRef-DOCUMENT", "DESCRIBES", "SPDXRef-Archive"),
            ("SPDXRef-Archive", "CONTAINS", "SPDXRef-Executable"),
            ("SPDXRef-Executable", "GENERATED_FROM", "SPDXRef-Package-ggctl-0.1.0"),
            ("SPDXRef-Package-ggctl-0.1.0", "DEPENDS_ON", "SPDXRef-Package-gateway-config-0.1.0"),
            ("SPDXRef-Package-gateway-config-0.1.0", "DEPENDS_ON", "SPDXRef-Package-serde-1.0.0"),
            ("SPDXRef-Package-cc-1.2.0", "BUILD_DEPENDENCY_OF", "SPDXRef-Package-gateway-config-0.1.0"),
        })
        serde = packages["SPDXRef-Package-serde-1.0.0"]
