//! Manual pages, generated from the command table.
//!
//! `ggctl help --man` writes ggctl(1) and `ggctl help --man COMMAND` writes
//! ggctl-COMMAND(1), in man(7) roff. A page says what `ggctl help` says, from
//! the same table and the same text, so the two cannot drift; the tests hold
//! every page to its help. A page names no date, path or platform, so every
//! build of one version writes the same bytes, which keeps the release
//! archives that install them under `man/man1` reproducible
//! (`scripts/ggctl_release.py`).

use crate::{
    cli::{CommandSpec, COMMANDS},
    diagnostic::Exit,
    help,
};

/// The `.TH` source and manual names.
const SOURCE: &str = concat!("ggctl ", env!("CARGO_PKG_VERSION"));
const MANUAL: &str = "GreenGateway Manual";

/// ggctl(1), or ggctl-COMMAND(1) for one command.
pub(crate) fn page(command: Option<&CommandSpec>) -> String {
    match command {
        Some(command) => command_page(command),
        None => overview_page(),
    }
}

fn overview_page() -> String {
    let mut page = title("ggctl");
    page.push_str(".SH NAME\n");
    push_line(&mut page, &escape(&format!("ggctl - {}", help::TAGLINE)));
    page.push_str(".SH SYNOPSIS\n");
    for (index, usage) in help::OVERVIEW_USAGE.iter().copied().enumerate() {
        if index > 0 {
            page.push_str(".br\n");
        }
        let (name, rest) = usage.split_once(' ').unwrap_or((usage, ""));
        push_line(&mut page, &format!("{} {}", bold(name), escape(rest)));
    }
    page.push_str(".SH DESCRIPTION\n");
    push_paragraphs(&mut page, help::OVERVIEW_NOTES);
    page.push_str(".SH COMMANDS\n");
    for command in COMMANDS {
        push_entry(&mut page, &bold(command.name), command.summary);
    }
    page.push_str(".SH EXIT STATUS\n");
    for exit in Exit::ALL {
        push_entry(&mut page, &bold(&exit.code().to_string()), exit.meaning());
    }
    page.push_str(".SH SEE ALSO\n");
    let pages: Vec<String> = COMMANDS
        .iter()
        .map(|command| format!("{}(1)", bold(&format!("ggctl-{}", command.name))))
        .collect();
    push_line(&mut page, &pages.join(", "));
    page
}

fn command_page(command: &CommandSpec) -> String {
    let name = format!("ggctl-{}", command.name);
    let mut page = title(&name);
    page.push_str(".SH NAME\n");
    push_line(&mut page, &escape(&format!("{name} - {}", command.summary)));
    page.push_str(".SH SYNOPSIS\n");
    let invocation = format!("ggctl {}", command.name);
    let usage = help::usage(command);
    let rest = usage.strip_prefix(&invocation).unwrap_or_default();
    push_line(&mut page, &format!("{}{}", bold(&invocation), escape(rest)));
    page.push_str(".SH DESCRIPTION\n");
    push_paragraphs(&mut page, command.description);
    if !command.arguments.is_empty() {
        page.push_str(".SH ARGUMENTS\n");
        for argument in command.arguments {
            push_entry(&mut page, &italic(argument.name), argument.help);
        }
    }
    page.push_str(".SH OPTIONS\n");
    for option in command.options {
        let mut tag = bold(option.name);
        if let Some((placeholder, _)) = option.value {
            tag.push(' ');
            tag.push_str(&italic(placeholder));
        }
        push_entry(&mut page, &tag, option.help);
    }
    let (names, description) = help::HELP_OPTION;
    let names: Vec<String> = names.iter().map(|name| bold(name)).collect();
    push_entry(&mut page, &names.join(", "), description);
    page.push_str(".SH SEE ALSO\n");
    push_line(&mut page, &format!("{}(1)", bold("ggctl")));
    page
}

/// The comment naming the generator, then the `.TH` line.
fn title(name: &str) -> String {
    format!(
        ".\\\" Generated by `ggctl help --man` from its command table.\n\
         .TH {} 1 \"\" \"{}\" \"{MANUAL}\"\n",
        escape(&name.to_ascii_uppercase()),
        escape(SOURCE)
    )
}

/// A `.TP` entry: the tag line, then its description.
fn push_entry(page: &mut String, tag: &str, description: &str) {
    page.push_str(".TP\n");
    push_line(page, tag);
    push_line(page, &escape(description));
}

/// Paragraphs, one input line each, separated by `.PP`.
fn push_paragraphs(page: &mut String, paragraphs: &[&str]) {
    for (index, paragraph) in paragraphs.iter().enumerate() {
        if index > 0 {
            page.push_str(".PP\n");
        }
        push_line(page, &escape(paragraph));
    }
}

/// One line of already escaped text. A line that would begin with a control
/// character is guarded with the zero-width `\&`, so text is never read as a
/// request.
fn push_line(page: &mut String, roff: &str) {
    if roff.starts_with(['.', '\'']) {
        page.push_str("\\&");
    }
    page.push_str(roff);
    page.push('\n');
}

fn bold(text: &str) -> String {
    format!("\\fB{}\\fR", escape(text))
}

fn italic(text: &str) -> String {
    format!("\\fI{}\\fR", escape(text))
}

/// Escapes text for roff: the escape character itself, and every hyphen, so
/// an option such as `--format` prints as typed rather than as dashes.
fn escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for character in text.chars() {
        match character {
            '\\' => escaped.push_str("\\e"),
            '-' => escaped.push_str("\\-"),
            other => escaped.push(other),
        }
    }
    escaped
}

#[cfg(test)]
mod tests {
    use super::*;

    /// What a reader of the page sees: its text lines with the escapes this
    /// module writes undone, requests and comments dropped, and whitespace
    /// collapsed.
    fn rendered(page: &str) -> String {
        let lines: Vec<String> = page
            .lines()
            .filter(|line| !line.starts_with('.'))
            .map(|line| {
                line.replace("\\fB", "")
                    .replace("\\fI", "")
                    .replace("\\fR", "")
                    .replace("\\&", "")
                    .replace("\\-", "-")
                    .replace("\\e", "\\")
            })
            .collect();
        collapsed(&lines.join(" "))
    }

    fn collapsed(text: &str) -> String {
        text.split_whitespace().collect::<Vec<_>>().join(" ")
    }

    /// The help text as the units a reader sees: each paragraph, each
    /// two-column entry with its wrapped continuation, and each usage line
    /// without its `Usage:` label. Section headings and the overview's
    /// versioned title line are left out; the page's own header carries them.
    fn help_blocks(help: &str) -> Vec<String> {
        fn finish(current: &mut String, blocks: &mut Vec<String>) {
            if !current.is_empty() {
                blocks.push(collapsed(current));
                current.clear();
            }
        }
        let mut blocks = Vec::new();
        let mut current = String::new();
        for (index, line) in help.lines().enumerate() {
            let heading = matches!(
                line,
                "Commands:" | "Exit codes:" | "Arguments:" | "Options:"
            );
            if line.is_empty() || heading || (index == 0 && line.starts_with("ggctl ")) {
                finish(&mut current, &mut blocks);
            } else if let Some(usage) = line.strip_prefix("Usage: ") {
                finish(&mut current, &mut blocks);
                blocks.push(collapsed(usage));
            } else if line.starts_with("       ggctl ") {
                blocks.push(collapsed(line));
            } else if line.starts_with("  ") && !line.starts_with("   ") {
                finish(&mut current, &mut blocks);
                current.push_str(line);
            } else {
                current.push(' ');
                current.push_str(line);
            }
        }
        finish(&mut current, &mut blocks);
        blocks
    }

    fn topics() -> impl Iterator<Item = Option<&'static CommandSpec>> {
        std::iter::once(None).chain(COMMANDS.iter().map(Some))
    }

    #[test]
    fn every_page_says_what_its_help_says() {
        for topic in topics() {
            let help = help::text(topic);
            let man = rendered(&page(topic));
            let blocks = help_blocks(&help);
            assert!(blocks.len() >= 4, "{help}");
            for block in blocks {
                assert!(man.contains(&block), "{block:?} is missing from\n{man}");
            }
        }
    }

    #[test]
    fn every_page_is_named_after_its_command_and_its_summary() {
        let overview = page(None);
        assert!(overview.contains("\n.TH GGCTL 1 \"\" \"ggctl "));
        assert!(rendered(&overview).starts_with("ggctl - the GreenGateway operator CLI "));
        for command in COMMANDS {
            let page = page(Some(command));
            let name = escape(&format!("GGCTL-{}", command.name.to_ascii_uppercase()));
            assert!(
                page.contains(&format!("\n.TH {name} 1 ")),
                "{}",
                command.name
            );
            assert!(rendered(&page).starts_with(&format!(
                "ggctl-{} - {} ggctl {}",
                command.name, command.summary, command.name
            )));
            assert!(rendered(&overview).contains(&format!("ggctl-{}(1)", command.name)));
        }
    }

    #[test]
    fn pages_are_ascii_roff_with_only_known_requests() {
        for topic in topics() {
            let page = page(topic);
            assert!(page.is_ascii());
            assert!(page.ends_with('\n') && !page.contains('\r'));
            assert_eq!(page, super::page(topic), "a page is deterministic");
            assert!(page.starts_with(".\\\" Generated by `ggctl help --man`"));
            for line in page.lines().skip(1) {
                if line.starts_with('.') {
                    let request = line.split(' ').next().unwrap_or_default();
                    assert!(
                        [".TH", ".SH", ".TP", ".PP", ".br"].contains(&request),
                        "{line}"
                    );
                } else {
                    assert!(!line.starts_with('\'') && !line.is_empty(), "{line:?}");
                    // Every backslash starts one of the escapes written here.
                    let mut rest = line;
                    while let Some(at) = rest.find('\\') {
                        rest = &rest[at + 1..];
                        assert!(
                            ["fB", "fI", "fR", "-", "e", "&"]
                                .iter()
                                .any(|escape| rest.starts_with(escape)),
                            "{line}"
                        );
                    }
                }
            }
        }
    }

    #[test]
    fn escaping_survives_hostile_text() {
        assert_eq!(escape(r"a-b\c"), r"a\-b\ec");
        let mut page = String::new();
        push_line(&mut page, ".SH injected");
        push_line(&mut page, "'br");
        push_line(&mut page, "plain .text");
        assert_eq!(page, "\\&.SH injected\n\\&'br\nplain .text\n");
        assert_eq!(bold("--man"), r"\fB\-\-man\fR");
        assert_eq!(italic("FILE"), r"\fIFILE\fR");
    }
}
